enum class ServerState { STOPPED, STARTING, READY, FAILED }

data class ServerStatus(
    val role: Role,
    val state: ServerState = ServerState.STOPPED,
    /** Why the server is FAILED (exit code / signal / last log line), or a note while STOPPED after a failure. */
    val reason: String? = null,
    val modelPath: String? = null,
    val port: Int = role.defaultPort,
    val pid: Long? = null,
    val args: List<String> = emptyList(),
    val startedAtMs: Long = 0L,
    /** Milliseconds from launch to READY (load time). */
    val readyAfterMs: Long? = null,
    /** Banner text for the UI: the server was killed and is being restarted, or was restarted, or will not be. Null normally. */
    val notice: String? = null,
    /** Automatic restarts used in the current failure episode (0 or 1). */
    val restarts: Int = 0,
    /** Which llama-server build this CHAT server runs on (GPU = OpenCL, CPU = i8mm); null for the other roles and while stopped. */
    val backend: Backend? = null,
) {
    /** File name without extension, e.g. "Qwen3.5-4B-Q4_K_M"; null for RPC or when stopped. */
    val modelName: String? get() = modelPath?.let { File(it).name.removeSuffix(".gguf") }
}

/**
 * Launches and supervises the shipped llama.cpp binaries (libllama-server.so, libllama-server-gpu.so, librpc-server.so) as
 * child processes of the app, from nativeLibraryDir (the only place an app may exec from). One process per [Role].
 * CHAT starts on the OpenCL (GPU) build and falls back to the CPU build when that does not get READY ([BackendPlan]);
 * [ServerStatus.backend] says which one runs. The embedder, rpc-server and a split chat server (`--rpc`) use the CPU build.
 *
 * Public API for other modules (MemoryCloud, Choir, Data Union):
 *  - [start] / [stop] / [stopAll] / [status] / [statusOf] / [logTail] / [rssKb] / [lastStats]
 *  - AppGraph.llm / AppGraph.embedder switch to real [LlamaServerClient]s while CHAT / EMBED are READY, and back to FakeLlmClient otherwise.
 *  - [realChatReady] / [realEmbedderReady]: true only while that role is READY with a real model (use these, not `is FakeLlmClient`).
 * Everything runs only while SwarmService is alive: it calls [onServiceStarted] and [onServiceStopped].
 */
object LlamaRuntime {
    private const val TAG = "LlamaRuntime"
    private const val READY_TIMEOUT_MS = 300_000L

    /** Tokens generated by the warm-up request on the chat server. */
    private const val WARMUP_TOKENS = 8

    /** The GPU build compiles kernels at its first start (a few seconds) and loads the weights into GPU buffers; past this the CPU build takes over. */
    private const val GPU_READY_TIMEOUT_MS = 120_000L
    private const val LOG_FILE_CAP = 8L * 1024 * 1024

    /** How long to wait for a killed orphan to vanish from /proc before its port is checked. */
    private const val ORPHAN_WAIT_MS = 5_000L

    private val scope = CoroutineScope(SupervisorJob() + Dispatchers.IO)
    private val locks = Role.entries.associateWith { Mutex() }

    /**
     * Status and epoch of every role. A start remembers the epoch it was requested under, a running server keeps it in its
     * [Running] record, and both give up (and stop writing status) when a [stop] or a newer start changed it: a Stop that
     * arrives while a start is queued, loading, or between a server's death and its restart can never be followed by a
     * server nobody asked for or by a stale STARTING / FAILED status.
     */
    private val board = StatusBoard()

    /** Held while a child is being launched and published in [running], and while orphans are scanned (an orphan scan must not kill a child that is about to be published). */
    private val procLock = Any()

    /**
     * [cpuOnly]: skip the GPU build (set when a server that had fallen back to the CPU is restarted).
     * [fallbackNote]: set when this start IS a fallback from a GPU server that died twice; shown as the banner of the CPU server.
     */
    private data class StartConfig(
        val modelPath: String?, val extraArgs: List<String>, val port: Int, val env: Map<String, String>,
        val cpuOnly: Boolean = false, val readyTimeoutMs: Long = READY_TIMEOUT_MS, val fallbackNote: String? = null,
    )

    private class Running(
        val role: Role,
        val process: Process,
        val ring: LogRing,
        val startedNs: Long,
        val cfg: StartConfig,
        val backend: Backend,
        /** The epoch of the start that launched this process; every later status write on its behalf checks it. */
        val epoch: Int,
    ) {
        @Volatile var stopRequested = false
        @Volatile var wasReady = false

        /** The thread that copies the child's output into [ring]; joined before the ring is read after an exit (the last lines arrive late). */
        @Volatile var pumpThread: Thread? = null
    }

    private val running = java.util.concurrent.ConcurrentHashMap<Role, Running>()

    /** Last stderr/log lines of a start that failed, or that fell back from the GPU to the CPU build; cleared by the next start. */
    private val lastErrors = java.util.concurrent.ConcurrentHashMap<Role, String>()

    /** The last lines (at most 2 KB) the failed or fallen-back server printed, for `/v1/models/state` `lastError`; null after a clean start. */
    fun lastError(role: Role): String? = lastErrors[role]

    /** State of every role. Collect it from the UI. */
    val status: StateFlow<Map<Role, ServerStatus>> = board.status

    private val _realChatReady = MutableStateFlow(false)

    /**
     * True only while CHAT is READY with a real model and AppGraph.llm already is the client for it (so reading AppGraph.llm
     * after seeing true never returns the fake client). False while stopped, loading, failed or restarting. Choir, Data Union
     * and MemoryCloud use this instead of testing `AppGraph.llm is FakeLlmClient`.
     */
    val realChatReady: StateFlow<Boolean> = _realChatReady.asStateFlow()

    private val _realEmbedderReady = MutableStateFlow(false)

    /** The same for the embedding server and AppGraph.embedder. */
    val realEmbedderReady: StateFlow<Boolean> = _realEmbedderReady.asStateFlow()

    /** Stats of the most recent generation on this phone (chat or bench). */
    val lastStats = MutableStateFlow<ChatStats?>(null)

    /** Wall time per text of the most recent embed() call. */
    val lastEmbedMsPerText = MutableStateFlow<Double?>(null)

    private val _speed = MutableStateFlow<Map<Role, SpeedSample>>(emptyMap())

    /**
     * The latest controlled speed measurement of each server: the warm-up request at load, then the benchmark (CHAT) or the
     * latest embedding call (EMBED). The Models tab shows these with what they were measured on and when.
     */
    val speed: StateFlow<Map<Role, SpeedSample>> = _speed.asStateFlow()

    internal fun publishSpeed(role: Role, sample: SpeedSample?) {
        _speed.update { if (sample != null) it + (role to sample) else it - role }
    }

    /** Called by the client after an embedding request. */
    internal fun recordEmbed(model: String, msPerText: Double) {
        lastEmbedMsPerText.value = msPerText
        publishSpeed(Role.EMBED, SpeedSample(model, SpeedSource.REQUEST, System.currentTimeMillis(), embedMsPerText = msPerText))
    }

    @Volatile private var serviceUp = false
    private var serviceJobs: List<Job> = emptyList()

    fun statusOf(role: Role): ServerStatus = board.statusOf(role)

    // ---- lifecycle tied to SwarmService ----

    /** Called by SwarmService after it entered the foreground. Wires AppGraph and loads the default models. */
    @Synchronized
    fun onServiceStarted() {
        if (serviceUp) return
        serviceUp = true
        val wire = scope.launch {
            board.status.collect { st ->
                val chat = st.getValue(Role.CHAT)
                val embed = st.getValue(Role.EMBED)
                // "ready" flags flip after the client swap on the way up and before it on the way down, so they never promise a client that is not there
                if (!chat.isRealReady()) _realChatReady.value = false
                if (!embed.isRealReady()) _realEmbedderReady.value = false
                syncClient(Role.CHAT, chat, AppGraph.llm) { AppGraph.llm = it }
                syncClient(Role.EMBED, embed, AppGraph.embedder) { AppGraph.embedder = it }
                if (chat.isRealReady()) _realChatReady.value = true
                if (embed.isRealReady()) _realEmbedderReady.value = true
                // one scheduler job at a time while the chat server is READY (parallel slots add no throughput), none otherwise
                val cap = if (chat.state == ServerState.READY) LlamaArgs.SCHED_CAPACITY else 0
                if (cap != schedCapacity) {
                    schedCapacity = cap
                    Sched.setCapacity(cap)
                }
            }
        }
        val load = scope.launch {
            awaitGone(killOrphans(), ORPHAN_WAIT_MS)
            if (ModelStore.autoload.value) loadDefaults() else Log.i(TAG, "autoload is off: no model is loaded at start")
        }
        serviceJobs = listOf(wire, load)
    }

    @Volatile private var schedCapacity = -1

    /**
     * Starts the catalog default chat and embedding models (Qwen3.5-4B, EmbeddingGemma-300M) when they are present.
     * Returns one handle per role that was started; roles whose file is missing are skipped. With [onlyMissing] a role that is
     * already READY or loading is left alone (the Models tab uses it so "Load models" never restarts a running server).
     */
    fun loadDefaults(onlyMissing: Boolean = false): List<Deferred<ServerStatus>> =
        (if (onlyMissing) rolesToLoad(statusOf(Role.CHAT).state, statusOf(Role.EMBED).state) else listOf(Role.CHAT, Role.EMBED)).mapNotNull { role ->
            ModelStore.autoLoadFile(role)?.let { startAsync(role, it.absolutePath) }
        }

    /** Called by SwarmService.onDestroy: kill every child, restore the fake clients. */
    @Synchronized
    fun onServiceStopped() {
        serviceUp = false
        serviceJobs.forEach { it.cancel() }
        serviceJobs = emptyList()
        stopAll()
        _realChatReady.value = false
        _realEmbedderReady.value = false
        AppGraph.llm = com.swarmos.app.llm.FakeLlmClient()
        AppGraph.embedder = com.swarmos.app.llm.FakeLlmClient()
        schedCapacity = 0
        Sched.setCapacity(0)
    }

    private fun syncClient(role: Role, st: ServerStatus, current: LlmClient, set: (LlmClient) -> Unit) {
        if (st.state == ServerState.READY) {
            val name = st.modelName ?: return
            val already = current is LlamaServerClient && current.modelName == name && current.port == st.port
            if (!already) set(LlamaServerClient(role, name, st.port))
        } else if (current is LlamaServerClient) {
            set(FakeLlmClient())
        }
    }

    // ---- start / stop ----

    /**
     * Starts [role] and suspends until it is READY or FAILED; returns the final status.
     * Restarts it when already running. [extraArgs] are appended after the defaults of [LlamaArgs] (the last flag wins),
     * [env] is added to the child's environment (LD_LIBRARY_PATH and LLAMA_CACHE are preset).
     * RPC takes no model. Must run while SwarmService is alive. CHAT and EMBED get one throwaway request before READY
     * (the first request after load pays a page-in penalty). A start that is superseded by a newer start of the same role,
     * or by [stop], gives up and returns the status at that moment (not READY).
     */
    suspend fun start(
        role: Role,
        modelPath: String?,
        extraArgs: List<String> = emptyList(),
        port: Int = role.defaultPort,
        env: Map<String, String> = emptyMap(),
        readyTimeoutMs: Long = READY_TIMEOUT_MS,
    ): ServerStatus = startAsync(role, modelPath, extraArgs, port, env, readyTimeoutMs).await()

    /** MemAvailable of this phone in kB from /proc/meminfo, null when it cannot be read. */
    private fun readMemAvailableKb(): Long? = runCatching { LoadPreflight.parseMemAvailableKb(File("/proc/meminfo").readText()) }.getOrNull()

    /** Same as [start] but returns at once; cancelling the caller never leaves a half-started server behind. */
    fun startAsync(
        role: Role,
        modelPath: String?,
        extraArgs: List<String> = emptyList(),
        port: Int = role.defaultPort,
        env: Map<String, String> = emptyMap(),
        readyTimeoutMs: Long = READY_TIMEOUT_MS,
    ): Deferred<ServerStatus> {
        // A newer start or a stop() after this point cancels this start; a pending automatic restart is superseded too.
        val epoch = board.newEpoch(role)
        val cfg = StartConfig(modelPath, extraArgs, port, env, readyTimeoutMs = readyTimeoutMs)
        return scope.async { startInternal(role, cfg, epoch, auto = false) }
    }

    /** Result of launching one server process: [retry] is true when the process failed for a reason worth trying the next backend for. */
    private class Attempt(val status: ServerStatus, val retry: Boolean)

    /** Announces the load on the phone's activity banner (with a Stop action) while it queues and runs, then starts under the role lock. */
    private suspend fun startInternal(role: Role, cfg: StartConfig, epoch: Int, auto: Boolean): ServerStatus {
        val text = ModelsActivity.loadText(role) ?: return startLocked(role, cfg, epoch, auto)
        val key = ModelsActivity.loadKey(role) + "-$epoch" // one entry per start: a superseded start must not clear the newer one
        ModelsActivity.set(key, text, onStop = { stop(role) })
        try {
            return startLocked(role, cfg, epoch, auto)
        } finally {
            ModelsActivity.end(key)
        }
    }

    private suspend fun startLocked(role: Role, cfg: StartConfig, epoch: Int, auto: Boolean): ServerStatus = locks.getValue(role).withLock {
        val modelPath = cfg.modelPath
        val port = cfg.port
        if (!board.isCurrent(role, epoch)) return@withLock statusOf(role) // stopped before this start began
        if (!auto) lastErrors.remove(role) // a new start of its own; an automatic restart keeps the detail of the death that caused it
        val prior = statusOf(role)
        stopProcess(role) // waits until the old process is gone, so its port is free
        val ctx = AppGraph.appContext
        if (!serviceUp) return@withLock fail(role, epoch, "SwarmService is not running", modelPath, port)
        // a phone at CRITICAL or worse takes on no new work, a model load included (ThermalGate)
        ThermalGate.decide(Bench.thermalStatusNow(), WorkKind.MODEL_LOAD).takeUnless { it.allowed }?.let {
            return@withLock fail(role, epoch, it.reason.orEmpty(), modelPath, port)
        }
        if (role != Role.RPC && (modelPath == null || !File(modelPath).isFile)) {
            return@withLock fail(role, epoch, "model file not found: $modelPath", modelPath, port)
        }
        // The old server of this role is already gone here, so MemAvailable is what the new load really gets. A load with extra
        // arguments (MemoryCloud's split and its one-phone baseline) is exempt, see LoadPreflight.applies.
        if (modelPath != null && LoadPreflight.applies(role, cfg.extraArgs)) {
            val file = File(modelPath)
            LoadPreflight.refusal(file.name, file.length(), readMemAvailableKb())?.let {
                return@withLock fail(role, epoch, it, modelPath, port)
            }
        }
        val libDir = File(ctx.applicationInfo.nativeLibraryDir)
        var plan = BackendPlan.choose(role, cfg.extraArgs, ModelStore.useGpu.value, File(libDir, LlamaArgs.GPU_BINARY).exists(), cfg.cpuOnly)
        // set when this start is itself a fallback from a GPU server that died twice
        var fallbackNote: String? = cfg.fallbackNote
        var gpuFailed = cfg.fallbackNote != null
        if (Backend.GPU in plan && GpuFailureMemory.skipGpu(ModelStore.gpuFailedStamp(), ModelStore.appStamp())) {
            // the GPU build failed on this install before: do not pay its start timeout again (cleared by the GPU switch or an app update)
            plan = listOf(Backend.CPU)
            fallbackNote = GpuFailureMemory.SKIPPED_NOTE
        }
        var last = statusOf(role)
        for (backend in plan) {
            val a = launchAttempt(role, cfg, epoch, auto, prior, backend, libDir, fallbackNote)
            last = a.status
            if (!a.retry) break
            // The GPU server did not get READY: say so, then try the CPU build (the next entry of the plan).
            gpuFailed = true
            fallbackNote = BackendPlan.fallbackNote(last.reason)
        }
        // remember a GPU failure only once the CPU build has served the same model: a broken model file fails on both and says nothing about the GPU
        if (gpuFailed && last.state == ServerState.READY && last.backend == Backend.CPU) ModelStore.markGpuFailed()
        last
    }

    /**
     * Launches [role] once on [backend] and waits for READY. A GPU attempt that fails (exec error, exit, no health, a failing
     * first request) reports `retry = true`; stops, supersession and CPU failures do not.
     */
    private suspend fun launchAttempt(
        role: Role, cfg: StartConfig, epoch: Int, auto: Boolean, prior: ServerStatus,
        backend: Backend, libDir: File, fallbackNote: String?,
    ): Attempt {
        val ctx = AppGraph.appContext
        val modelPath = cfg.modelPath
        val port = cfg.port
        val gpu = backend == Backend.GPU
        val shownBackend = if (role == Role.CHAT) backend else null
        val retryOnFail = gpu
        val bin = File(libDir, LlamaArgs.binaryFor(role, backend))
        if (!bin.exists()) return Attempt(fail(role, epoch, "${bin.name} is not in the APK (nativeLibraryDir ${bin.parent})", modelPath, port, shownBackend), retryOnFail)
        if (!ensurePortFree(role, port)) {
            return Attempt(fail(role, epoch, "port $port is still in use after two retries (another app or an adb shell process holds it)", modelPath, port, shownBackend), false)
        }
        if (!board.isCurrent(role, epoch)) return Attempt(statusOf(role), false)
        // the child inherits the cores this process may use now (fewer when the app is in the background), so size the CPU chat build from them
        val cmd = listOf(bin.absolutePath) + LlamaArgs.build(role, modelPath, port, cfg.extraArgs, backend, allowedCores = CpuSet.allowed())
        val args = LlamaArgs.redacted(cmd.drop(1)) // what the status and the log show: never the API key
        val logFile = File(File(ctx.filesDir, "logs").apply { mkdirs() }, "${role.tag}.log")
        val ring = LogRing()
        val restarts = if (auto) prior.restarts else 0
        val startingNotice = fallbackNote ?: if (auto) prior.notice?.restartingNow() else null
        val announced = board.setIfCurrent(role, epoch) {
            ServerStatus(role, ServerState.STARTING, null, modelPath, port, null, args, System.currentTimeMillis(), null, startingNotice, restarts, shownBackend)
        }
        if (!announced) return Attempt(statusOf(role), false) // a stop() slipped in: it published STOPPED, keep it
        val run: Running
        synchronized(procLock) {
            val proc = try {
                ProcessBuilder(cmd)
                    .directory(ctx.filesDir)
                    .redirectErrorStream(true)
                    .apply {
                        environment()["LD_LIBRARY_PATH"] = LlamaArgs.ldLibraryPath(ctx.applicationInfo.nativeLibraryDir, role, backend)
                        environment()["LLAMA_CACHE"] = File(ctx.filesDir, "llama-cache").apply { mkdirs() }.path // rpc-server -c needs it (no $HOME on Android)
                        environment().putAll(cfg.env)
                    }
                    .start()
            } catch (e: Exception) {
                return Attempt(fail(role, epoch, "cannot exec ${bin.name}: ${e.message}", modelPath, port, shownBackend), retryOnFail)
            }
            run = Running(role, proc, ring, System.nanoTime(), cfg, backend, epoch)
            running[role] = run
        }
        val proc = run.process
        // stop() may have run between the epoch check above and the publish just now: it found nothing to kill, so do it here
        val pid = pidOf(proc)
        if (!board.setIfCurrent(role, epoch) { it.copy(pid = pid) }) {
            run.stopRequested = true
            running.remove(role, run)
            killProcess(proc)
            return Attempt(statusOf(role), false)
        }
        Log.i(TAG, "${role.tag}: started on $backend pid=$pid ${(listOf(bin.absolutePath) + args).joinToString(" ")}")
        pump(run, logFile)
        watchExit(run)

        // wait for readiness (the GPU build gets a shorter deadline: the CPU fallback is waiting)
        val deadlineMs = if (gpu) GPU_READY_TIMEOUT_MS else cfg.readyTimeoutMs
        val deadline = System.nanoTime() + deadlineMs * 1_000_000
        while (System.nanoTime() < deadline) {
            if (!proc.isAlive) break
            if (!board.isCurrent(role, epoch)) { // stopped, or superseded by a newer start: stop loading at once
                run.stopRequested = true
                running.remove(role, run)
                killProcess(proc)
                return Attempt(statusOf(role), false)
            }
            if (probe(role, port)) {
                // A health answer only counts if OUR process is still alive a moment later (guards against a foreign server on the port).
                delay(400)
                if (!proc.isAlive || !probe(role, port)) continue
                val warm = warmUp(role, port, File(modelPath ?: "").name.removeSuffix(".gguf"))
                if (run.stopRequested || !board.isCurrent(role, epoch)) return Attempt(statusOf(role), false)
                if (!proc.isAlive) break
                if (gpu && !warm.ok) { // READY on paper, but the first generation failed on the GPU: use the CPU build instead
                    run.stopRequested = true
                    running.remove(role, run)
                    killProcess(proc)
                    waitFor(proc, 4_000)
                    return Attempt(fail(role, epoch, "the first request failed on the GPU", modelPath, port, shownBackend, errorDetail(run, ring)), true)
                }
                val ms = (System.nanoTime() - run.startedNs) / 1_000_000
                run.wasReady = true
                val doneNotice = fallbackNote ?: if (auto) "Restarted automatically after the server was killed." else null
                publishSpeed(role, warm.sample) // before READY lands, so the row never shows a loaded server without its numbers
                if (!board.setIfCurrent(role, epoch) { it.copy(state = ServerState.READY, readyAfterMs = ms, notice = doneNotice) }) {
                    // a stop() or a newer start got in between and owns the status now: this server is not wanted
                    run.stopRequested = true
                    running.remove(role, run)
                    killProcess(proc)
                    return Attempt(statusOf(role), false)
                }
                Log.i(TAG, "${role.tag}: READY on $backend after $ms ms")
                return Attempt(statusOf(role), false)
            }
            delay(300)
        }
        if (proc.isAlive) {
            run.stopRequested = true
            running.remove(role, run)
            killProcess(proc)
            waitFor(proc, 4_000)
            return Attempt(fail(role, epoch, "not ready after ${deadlineMs / 1000} s; ${ring.tail(1).lastOrNull().orEmpty()}", modelPath, port, shownBackend, errorDetail(run, ring)), retryOnFail)
        }
        if (run.stopRequested) return Attempt(statusOf(role), false)
        run.stopRequested = true // the exit is reported here, not by watchExit
        running.remove(role, run)
        val code = runCatching { proc.exitValue() }.getOrDefault(-1)
        val detail = errorDetail(run, ring) // joins the log thread first: the last lines of a dead process arrive late
        return Attempt(fail(role, epoch, "${ProcInfo.describeExit(code)} during start; last log: ${ring.tail(3).joinToString(" | ")}", modelPath, port, shownBackend, detail), retryOnFail)
    }

    /**
     * Stops [role] (SIGTERM, then SIGKILL after 3 s). Safe to call when it is not running, and safe while a start for this
     * role is queued, checking ports or loading, or while a killed server waits for its restart: all of those are cancelled
     * (see [StatusBoard]) instead of racing with this stop, and none of them can overwrite the STOPPED it publishes.
     */
    fun stop(role: Role) {
        val run = board.stop(role) { running.remove(role) }
        lastErrors.remove(role)
        if (run != null) {
            run.stopRequested = true
            killProcess(run.process)
        }
    }

    /** Stops every role. Non-blocking for the caller beyond the SIGTERM; a watchdog escalates to SIGKILL. */
    fun stopAll() {
        for (r in Role.entries) stop(r)
    }

    /** Called by a start that already holds the role lock: kills the old process of [role] and waits until it is really gone. */
    private fun stopProcess(role: Role) {
        val run = running.remove(role) ?: return
        run.stopRequested = true
        killProcess(run.process)
        board.set(role) { ServerStatus(role, port = it.port) }
        if (!waitFor(run.process, 4_000)) {
            run.process.destroyForcibly()
            waitFor(run.process, 2_000)
        }
    }

    /**
     * True when [port] can be bound on this phone. Loopback is shared by every app and every adb shell process, so a
     * foreign server on the same port would otherwise make our /health probe succeed against the wrong process.
     */
    private fun portFree(role: Role, port: Int): Boolean = try {
        java.net.ServerSocket().use { s ->
            s.reuseAddress = true
            s.bind(if (role == Role.RPC) InetSocketAddress(port) else InetSocketAddress("127.0.0.1", port))
        }
        true
    } catch (_: Exception) {
        false
    }

    private fun waitForPort(role: Role, port: Int, ms: Long): Boolean {
        val end = System.currentTimeMillis() + ms
        while (System.currentTimeMillis() < end) {
            if (portFree(role, port)) return true
            Thread.sleep(150)
        }
        return portFree(role, port)
    }

    /**
     * Frees [port] for a new server: the first try, then two retries, each after killing this app's stale servers (left
     * by an earlier app process) and waiting until they have really vanished from /proc (a SIGKILL is asynchronous).
     */
    private suspend fun ensurePortFree(role: Role, port: Int): Boolean {
        if (waitForPort(role, port, 1_500)) return true
        repeat(2) {
            awaitGone(killOrphans(), ORPHAN_WAIT_MS)
            if (waitForPort(role, port, 3_000)) return true
        }
        return false
    }

    /** Publishes FAILED unless a stop() or a newer start owns the status by now (then it is left alone). Returns the status as it stands. */
    private fun fail(role: Role, epoch: Int, reason: String, modelPath: String?, port: Int, backend: Backend? = null, detail: String? = null): ServerStatus {
        Log.e(TAG, "${role.tag}: FAILED: $reason")
        if (board.isCurrent(role, epoch)) lastErrors[role] = ProcInfo.errorDetail(listOf(detail ?: reason))
        board.setIfCurrent(role, epoch) {
            val note = if (it.restarts > 0) "The automatic restart failed. Tap Load to start it again." else null
            ServerStatus(role, ServerState.FAILED, reason, modelPath, port, null, it.args, it.startedAtMs, null, note, it.restarts, backend)
        }
        return statusOf(role)
    }

    private fun killProcess(p: Process) {
        p.destroy() // SIGTERM
        scope.launch {
            if (!waitFor(p, 3_000)) {
                p.destroyForcibly() // SIGKILL
            }
        }
    }

    private fun waitFor(p: Process, ms: Long): Boolean {
        val end = System.currentTimeMillis() + ms
        while (System.currentTimeMillis() < end) {
            if (!p.isAlive) return true
            Thread.sleep(50)
        }
        return !p.isAlive
    }

    /** Copies the child's stdout+stderr to the ring buffer and to filesDir/logs/<role>.log (truncated at each start, capped). */
    private fun pump(run: Running, logFile: File) {
        run.pumpThread = Thread({
            try {
                logFile.bufferedWriter().use { w ->
                    var written = 0L
                    run.process.inputStream.bufferedReader().forEachLine { line ->
                        run.ring.add(line)
                        if (written < LOG_FILE_CAP) {
                            w.write(line); w.newLine(); w.flush()
                            written += line.length + 1
                        }
                    }
                }
            } catch (_: Exception) {
                // stream closed when the process died
            }
        }, "llama-log-${run.role.tag}").apply { isDaemon = true; start() }
    }

    /** The last lines the child printed (stderr included), at most 2 KB, for /v1/models/state `lastError`. Waits briefly for the output of a process that just exited. */
    private fun errorDetail(run: Running?, ring: LogRing, lastLine: String? = null): String {
        if (run != null && !run.process.isAlive) runCatching { run.pumpThread?.join(1_500) }
        return ProcInfo.errorDetail(ring.tail(60) + listOfNotNull(lastLine))
    }

    /**
     * Reports unexpected exits (this is the evidence for the phantom-process / OriginOS question) and, when
     * [RestartPolicy] allows, restarts the server once after a backoff with a banner ([ServerStatus.notice]).
     */
    private fun watchExit(run: Running) {
        scope.launch {
            val code = run.process.waitFor()
            val aliveMs = (System.nanoTime() - run.startedNs) / 1_000_000
            if (run.stopRequested) return@launch
            if (!run.wasReady) return@launch // a server that dies while it starts is reported (and, for the GPU build, retried on the CPU) by its start
            val last = run.ring.tail(3).joinToString(" | ")
            val what = ProcInfo.describeExit(code)
            val reason = "$what after ${aliveMs / 1000} s; last log: $last"
            Log.e(TAG, "${run.role.tag}: DIED pid=${pidOf(run.process)} $reason")
            running.remove(run.role, run)
            val role = run.role
            val cfg = run.cfg
            if (board.isCurrent(role, run.epoch)) {
                // the exit line goes last: the 2 KB cap drops the oldest lines, and how it died is the most useful part
                lastErrors[role] = errorDetail(run, run.ring, "[exit] $what after ${aliveMs / 1000} s")
            }
            // Every step below is under the epoch this server was STARTED under (not the one at death time), so a stop()
            // between the death and the restart is honoured and never followed by a stale FAILED or STARTING.
            board.reportUnexpectedExit(
                role, run.epoch, run.wasReady, { serviceUp }, aliveMs, cfg.extraArgs, what,
                failedStatus = {
                    ServerStatus(role, ServerState.FAILED, reason, cfg.modelPath, cfg.port, null, it.args, it.startedAtMs, null, null, it.restarts, it.backend)
                },
                wait = { delay(it) },
                restart = { cpuFallback ->
                    // A GPU server that was killed is restarted once on the GPU (with the start-time CPU fallback); when it dies again
                    // inside the stable window (cpuFallback) it is started once on the CPU build, with the usual fallback banner.
                    // A CPU server stays on the CPU.
                    val again = cfg.copy(
                        cpuOnly = cfg.cpuOnly || run.backend == Backend.CPU || cpuFallback,
                        fallbackNote = if (cpuFallback) BackendPlan.fallbackNote(what) else null,
                    )
                    startInternal(role, again, run.epoch, auto = true)
                },
                backend = run.backend,
            )
        }
    }

    /**
     * One short request (8 tokens on the chat server) so the weights are paged in before the server is reported READY; its own
     * timings become the speed shown on the Models tab right after a load. [WarmUp.ok] is true when the server answered with a 2xx
     * (always true for RPC). A failing warm-up is ignored on the CPU build and sends the GPU build to the CPU fallback.
     */
    private fun warmUp(role: Role, port: Int, model: String): WarmUp {
        val (path, body) = when (role) {
            // 8 tokens, not 1: a decode speed needs a few generated tokens
            Role.CHAT -> "/v1/chat/completions" to
                """{"messages":[{"role":"user","content":"Hi"}],"max_tokens":$WARMUP_TOKENS,"temperature":0,"chat_template_kwargs":{"enable_thinking":false}}"""
            Role.EMBED -> "/v1/embeddings" to """{"input":["warm up"]}"""
            Role.RPC -> return WarmUp(true, null)
        }
        return try {
            val c = LlamaHttp.post("http://127.0.0.1:$port$path", body, 120_000)
            val (ok, text) = try {
                val text = LlamaHttp.readBody(c)
                (c.responseCode in 200..299) to text
            } finally {
                c.disconnect()
            }
            if (!ok) return WarmUp(false, null)
            val now = System.currentTimeMillis()
            val sample = when (role) {
                // the first request's own timings: the weights are still being paged in, which the caption on the Models tab says
                Role.CHAT -> runCatching { SpeedSample.fromStats(model, SpeedSource.LOAD, now, LlamaJson.parseChatResponse(text).stats) }.getOrNull()
                Role.EMBED -> embedLatency(port, model)
                Role.RPC -> null
            }
            WarmUp(true, sample)
        } catch (_: Exception) {
            WarmUp(false, null)
        }
    }

    /** One more timed embedding request after the throwaway one: what a caller of embed() waits for per text on a warm server. */
    private fun embedLatency(port: Int, model: String): SpeedSample? = try {
        val t0 = System.nanoTime()
        val c = LlamaHttp.post("http://127.0.0.1:$port/v1/embeddings", """{"input":["A warranty bill for a laptop purchase."]}""", 60_000)
        try {
            LlamaHttp.readBody(c)
            if (c.responseCode in 200..299) {
                SpeedSample(model, SpeedSource.LOAD, System.currentTimeMillis(), embedMsPerText = (System.nanoTime() - t0) / 1e6)
            } else {
                null
            }
        } finally {
            c.disconnect()
        }
    } catch (_: Exception) {
        null
    }

    /** [ok]: the server answered the warm-up request; [sample]: its measured speed, when the response carried timings. */
    private class WarmUp(val ok: Boolean, val sample: SpeedSample?)

    private fun probe(role: Role, port: Int): Boolean =
        if (role == Role.RPC) {
            // rpc-server may listen on the link address only (-H <ip>), where 127.0.0.1 is refused: probe where it was told to bind
            val a = statusOf(role).args
            val host = a.lastIndexOf("-H").takeIf { it >= 0 }?.let { a.getOrNull(it + 1) }?.takeIf { it != "0.0.0.0" } ?: "127.0.0.1"
            try {
                Socket().use { it.connect(InetSocketAddress(host, port), 500); true }
            } catch (_: Exception) {
                false
            }
        } else {
            LlamaHttp.healthOk(port)
        }

